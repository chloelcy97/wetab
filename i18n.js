/* 第一次打开时按浏览器语言猜，之后以用户选的为准 */
function detect() {
  const nav = (navigator.languages || [navigator.language || 'en']).join(',').toLowerCase();
  return /\bzh\b|zh-/.test(nav) ? 'zh' : 'en';
}

let lang = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && S[saved]) return saved;
  } catch {}
  return detect();
})();

export const getLang = () => lang;

/* <html lang> 和标签页标题都跟着走。lang 属性屏幕阅读器和浏览器的翻译提示都看。
   放在 applyLang 里，加载时和切换时走同一条路，不会漏。 */
function applyLang() {
  // 必须和文案实际用的字形一致。之前写的是 zh-Hant-HK（繁体香港），
  // 而文案是简体、字体栈要的是 PingFang SC —— 浏览器会按繁体的字形变体去渲染简体字，
  // 字没错，形却是歪的，看上去就像打错了字。
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
  document.title = t('app.title');
}
applyLang();

export function setLang(next) {
  if (!S[next]) return;
  lang = next;
  try { localStorage.setItem(LANG_KEY, next); } catch {}
  applyLang();
}

/** 查不到的 key 直接把 key 还回去，缺翻译时界面还能用，也一眼看得出漏了哪条 */
export function t(key, ...args) {
  const v = S[lang][key] ?? S.zh[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}
